#!/usr/bin/env python3
"""Generate native craft silhouettes from RGBA imports, without a runtime image dependency."""
import runpy
from pathlib import Path
root=Path(__file__).resolve().parents[1]
read=runpy.run_path(str(root/'tools/gen_collision_masks.py'))['read']
out=['// Generated by tools/gen_ship_masks.py.','using TerraCommand.Common.Actors;','namespace TerraCommand.Common.Physics {','public static class ShipCollisionMasks {']
for name,file in [('Rocket','CargoShip'),('Dropship','Dropship'),('Crate','DropCrate'),('RocketGear','RocketLeg4'),('DropshipHatchLeft','DropshipHatchLeft'),('DropshipHatchRight','DropshipHatchRight'),('DropshipBody','DropshipBody'),('DropshipEngineLeft','DropshipEngineLeft'),('DropshipEngineRight','DropshipEngineRight')]:
 w,h,rows=read(root/f'TerraCommand/Content/NPCs/{file}.png')
 filled={(x//2,y//2) for y in range(0,h,2) for x in range(0,w,2) if any(rows[yy][xx*4+3]>127 for yy in range(y,min(y+2,h)) for xx in range(x,min(x+2,w)))}
 edge={p for p in filled if any((p[0]+dx,p[1]+dy) not in filled for dx,dy in [(1,0),(-1,0),(0,1),(0,-1)])}
 for suffix,points in [('Hull',edge),('Fill',filled)]:
  values=[v for x,y in sorted(points,key=lambda p:(p[1],p[0])) for v in (x*2+1,y*2+1)]
  out.append(f'public static readonly ContactMask {name}{suffix} = new({w},{h},new short[] {{'+','.join(map(str,values))+'});')
out+=['}','}'];(root/'TerraCommand/Common/Physics/ShipCollisionMasks.Generated.cs').write_text('\n'.join(out)+'\n')
