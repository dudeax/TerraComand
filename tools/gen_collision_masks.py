#!/usr/bin/env python3
"""Derive contact samples from existing RGBA actor sprites. No image assets are modified."""
from pathlib import Path
import struct,zlib
root=Path(__file__).resolve().parent.parent

def read(path):
 b=path.read_bytes(); off=8; data=b''
 while off<len(b):
  n=struct.unpack_from('>I',b,off)[0];t=b[off+4:off+8];d=b[off+8:off+8+n];off+=n+12
  if t==b'IHDR': w,h,depth,colour,*_=struct.unpack('>IIBBBBB',d);assert (depth,colour)==(8,6)
  if t==b'IDAT':data+=d
 raw=zlib.decompress(data); rows=[];prev=[0]*(w*4);k=0
 def paeth(a,b,c):
  p=a+b-c; d=[abs(p-a),abs(p-b),abs(p-c)];return [a,b,c][d.index(min(d))]
 for y in range(h):
  f=raw[k];k+=1;row=[]
  for x in range(w*4):
   a=row[x-4] if x>=4 else 0;up=prev[x];c=prev[x-4] if x>=4 else 0
   v=raw[k]+[0,a,up,(a+up)//2,paeth(a,up,c)][f];k+=1;row.append(v&255)
  rows.append(row);prev=row
 return w,h,rows
out=['// Generated by tools/gen_collision_masks.py from the existing actor sprite alpha channels.','using Microsoft.Xna.Framework;','namespace TerraCommand.Common.Actors {','public static class ActorSpriteMasks {','public static ContactMask Get(ActorKind kind, string part) => (kind, part) switch {']
def name(k,p):return k+p
allparts=[]
for kind in ('Soldier','Light','Heavy','Brain','Crab','Turret'):
 for p in sorted((root/'TerraCommand/Content/Actors'/kind).glob('*.png')):
  if p.stem.startswith(('ArmFront','ArmBack','LegFront','LegBack')) or p.stem == 'Hand': continue
  w,h,rows=read(p);points=[]
  for y in range(0,h,2):
   for x in range(0,w,2):
    if any(rows[yy][xx*4+3]>127 for yy in range(y,min(y+2,h)) for xx in range(x,min(x+2,w))):points.extend((x+1,y+1))
  allparts.append((name(kind,p.stem),w,h,points));out.append(f'(ActorKind.{kind}, "{p.stem}") => {name(kind,p.stem)},')
# Shared jetpack
w,h,rows=read(root/'TerraCommand/Content/Actors/Jetpack.png');points=[]
for y in range(0,h,2):
 for x in range(0,w,2):
  if rows[y][x*4+3]>127:points.extend((x+1,y+1))
allparts.append(('Jetpack',w,h,points));out+=['(_, "Jetpack") => Jetpack,','_ => throw new System.ArgumentException($"No collision mask for {kind}/{part}"),','};']
for n,w,h,pts in allparts:out.append(f'public static readonly ContactMask {n} = new({w}, {h}, new short[] {{'+','.join(map(str,pts))+'});')
out+=['}','}']
p=root/'TerraCommand/Common/Actors/ActorSpriteMasks.Generated.cs';p.write_text('\n'.join(out)+'\n');print('Generated',len(allparts),'masks')
