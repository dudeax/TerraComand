#!/usr/bin/env python3
from pathlib import Path
import runpy
root=Path(__file__).resolve().parents[1]
read=runpy.run_path(str(root/'tools/gen_collision_masks.py'))['read']
out=['// Generated by tools/gen_limb_masks.py.','namespace TerraCommand.Common.Actors {','public static class DetachedLimbMasks {','public static ContactMask Get(ActorKind kind,int limb,int frame) => (kind,limb,frame) switch {']
for directory in sorted((root/'TerraCommand/Content/Actors').iterdir()):
 if not directory.is_dir(): continue
 for limb,part in enumerate(['LegFront','LegBack','ArmFront','ArmBack']):
  if directory.name=='Crab' and limb>=2: part=['LegFront','LegBack'][limb%2]
  for frame in range(6):
   file=directory/f'{part}{frame}.png'
   if not file.exists(): continue
   w,h,rows=read(file)
   points=[v for y in range(0,h,2) for x in range(0,w,2) if any(rows[yy][xx*4+3]>127 for yy in range(y,min(y+2,h)) for xx in range(x,min(x+2,w))) for v in (x+1,y+1)]
   out.append(f'(ActorKind.{directory.name},{limb},{frame})=>new({w},{h},new short[]{{'+','.join(map(str,points))+'}),')
out+=['_=>throw new System.ArgumentOutOfRangeException(nameof(frame)),','};','}','}']
(root/'TerraCommand/Common/Actors/DetachedLimbMasks.Generated.cs').write_text('\n'.join(out)+'\n')
